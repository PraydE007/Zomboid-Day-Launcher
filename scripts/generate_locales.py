# Write each locale out to its JSON file
created_langs = []
for code, data in locales.items():
    # Merge with en as fallback for any omitted key
    full_data = {}
    for k, v in en.items():
        full_data[k] = data.get(k, v)
    
    target_path = LOCALES_DIR / f"{code}.json"
    with open(target_path, "w", encoding="utf-8") as f:
        json.dump(full_data, f, indent=2, ensure_ascii=False)
    created_langs.append(code)

